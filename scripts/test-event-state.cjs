const fs = require('fs');
const ts = require(process.cwd() + '/node_modules/typescript');
const assert = require('node:assert/strict');
const source = fs.readFileSync('src/utils/eventState.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const moduleObject = {exports:{}};
new Function('exports', 'module', compiled)(moduleObject.exports,moduleObject);
const {eventState, addVolunteer, upcomingEvents} = moduleObject.exports;
const fixture = {id:'event', volunteersIds:['other'], volunteersNeeded:2, dateTime:'2027-01-01T00:00:00Z'};
assert.equal(eventState(fixture,'me').status,'1 of 2');
assert.equal(eventState(fixture,'me').canVolunteer,true);
assert.equal(eventState(fixture,'me').canShare,true);
const joined = addVolunteer(fixture,'me');
assert.equal(eventState(joined,'me').status,'volunteered');
assert.equal(eventState(joined,'me').applied,true);
assert.equal(eventState(joined,'me').canShare,true);
assert.equal(eventState(joined,'me').canVolunteer,false);
assert.equal(eventState(joined,'outsider').status,'team is full');
assert.equal(eventState(joined,'outsider').canShare,false);
assert.equal(eventState(joined,'outsider').canVolunteer,false);
assert.equal(addVolunteer(joined,'me'),joined);
assert.equal(addVolunteer(joined,'outsider'),joined);
assert.deepEqual(fixture.volunteersIds,['other']);
assert.equal(eventState(fixture,undefined).applied,false);
const data = JSON.parse(fs.readFileSync('db.json','utf8'));
assert.equal(upcomingEvents(data.events, new Date('2026-10-02').getTime()).length,3);
console.log('Passed: open, applied, full, applied/full precedence, duplicate/full registration, immutable update, signed-out user, and past-event filtering.');
